import { DESKTOP_CHANNELS, isDesktopReleaseRuntime, isDesktopTarget, isWindowsDesktopTarget, supportsDesktopReleaseRuntime, type DesktopChannel } from '@cwnupaa/proctor-shared';
import { desktopUpdateMetadata, getDesktopUpdaterReleases } from '@/lib/desktop-releases';
export const dynamic = 'force-dynamic';
export async function GET(request: Request, { params }: { params: Promise<{ channel: string; target: string; filename: string }> }) {
  const { channel, target, filename } = await params;
  const runtime = new URL(request.url).searchParams.get('runtime');
  if (!DESKTOP_CHANNELS.includes(channel as DesktopChannel) || !isDesktopTarget(target) || filename !== (isWindowsDesktopTarget(target) ? 'latest.yml' : 'latest-mac.yml')
    || runtime !== null && !isDesktopReleaseRuntime(runtime)) return new Response('Not found', { status: 404 });
  if (!supportsDesktopReleaseRuntime(target, runtime ?? undefined)) return new Response('Not found', { status: 404 });
  try {
    const [release] = await getDesktopUpdaterReleases(channel as DesktopChannel, runtime ?? undefined, false, target);
    if (!release) return new Response('Release not published', { status: 404 });
    // JSON is a YAML subset; artifact locations are always generated by this server.
    return Response.json(desktopUpdateMetadata(release), { headers: { 'Content-Type': 'application/yaml; charset=utf-8', 'Cache-Control': 'no-store' } });
  } catch { return new Response('Release service unavailable', { status: 503 }); }
}
