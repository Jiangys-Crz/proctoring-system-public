import { DESKTOP_CHANNELS, isDesktopTarget, type DesktopChannel } from '@cwnupaa/proctor-shared';
import { desktopUpdateMetadata, getDesktopReleases } from '@/lib/desktop-releases';
export const dynamic = 'force-dynamic';
export async function GET(_request: Request, { params }: { params: Promise<{ channel: string; target: string; filename: string }> }) {
  const { channel, target, filename } = await params;
  if (!DESKTOP_CHANNELS.includes(channel as DesktopChannel) || !isDesktopTarget(target) || filename !== (target === 'windows' ? 'latest.yml' : 'latest-mac.yml')) return new Response('Not found', { status: 404 });
  try {
    const release = (await getDesktopReleases(channel as DesktopChannel)).find(item => item.target === target);
    if (!release) return new Response('Release not published', { status: 404 });
    // JSON is a YAML subset; artifact locations are always generated by this server.
    return Response.json(desktopUpdateMetadata(release), { headers: { 'Content-Type': 'application/yaml; charset=utf-8', 'Cache-Control': 'no-store' } });
  } catch { return new Response('Release service unavailable', { status: 503 }); }
}
